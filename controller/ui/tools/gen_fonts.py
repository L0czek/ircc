#!/usr/bin/env python3
"""Generate controller/ui/src/fonts.cc from X11 misc-fixed BDF fonts.

The fonts are the public-domain "misc-fixed" fonts (xorg font-misc-misc, also shipped
in the embedded-graphics crate under fonts/src). Usage:

    python3 controller/ui/tools/gen_fonts.py <dir with 5x7.bdf 6x10.bdf 10x20.bdf> controller/ui/src/fonts.cc

Glyph set: ASCII 0x20..0x7E plus the extra code points below (when the font has them).
Bitmap layout: per glyph `height` rows of `bytes_per_row` bytes, MSB = leftmost pixel,
cell = the font bounding box, baseline at `ascent`.
"""
import os
import sys

EXTRA = [0xB0, 0xB1, 0xB5, 0x3A9, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193,
         0x25B2, 0x25B6, 0x25BC, 0x25C0]

FONTS = [  # (file, C++ name)
    ("5x7.bdf", "kFontSmall"),
    ("6x10.bdf", "kFontBody"),
    ("10x20.bdf", "kFontBig"),
]


def parse_bdf(path):
    glyphs = {}
    font = {}
    with open(path, encoding="latin-1") as f:
        lines = iter(f.read().splitlines())
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "FONTBOUNDINGBOX":
            font["bbx"] = tuple(int(v) for v in parts[1:5])
        elif parts[0] == "FONT_ASCENT":
            font["ascent"] = int(parts[1])
        elif parts[0] == "STARTCHAR":
            enc = None
            bbx = None
            rows = []
            for line in lines:
                p = line.split()
                if not p:
                    continue
                if p[0] == "ENCODING":
                    enc = int(p[1])
                elif p[0] == "BBX":
                    bbx = tuple(int(v) for v in p[1:5])
                elif p[0] == "BITMAP":
                    for line in lines:
                        if line.strip() == "ENDCHAR":
                            break
                        rows.append(int(line.strip(), 16))
                    break
            glyphs[enc] = (bbx, rows)
    return font, glyphs


def render(font, glyph):
    fw, fh, fx, fy = font["bbx"]
    ascent = font["ascent"]
    (gw, gh, gx, gy), rows = glyph
    bpr = (fw + 7) // 8
    cell = [[0] * fw for _ in range(fh)]
    src_bits = ((gw + 7) // 8) * 8
    top = ascent - (gy + gh)
    for r, value in enumerate(rows):
        for c in range(gw):
            if value & (1 << (src_bits - 1 - c)):
                x = gx - fx + c
                y = top + r
                if 0 <= x < fw and 0 <= y < fh:
                    cell[y][x] = 1
    out = []
    for y in range(fh):
        for b in range(bpr):
            byte = 0
            for i in range(8):
                x = b * 8 + i
                if x < fw and cell[y][x]:
                    byte |= 0x80 >> i
            out.append(byte)
    return out


def main():
    src_dir, out_path = sys.argv[1], sys.argv[2]
    out = []
    out.append("// Generated by controller/ui/tools/gen_fonts.py from the public-domain X11")
    out.append("// misc-fixed BDF fonts. Do not edit.")
    out.append('#include "ui/font.hpp"')
    out.append("")
    out.append("namespace ui {")
    out.append("")
    for file, name in FONTS:
        font, glyphs = parse_bdf(os.path.join(src_dir, file))
        fw, fh, _, _ = font["bbx"]
        bpr = (fw + 7) // 8
        cps = [c for c in list(range(0x20, 0x7F)) + EXTRA if c in glyphs]
        tag = name[len("kFont"):].lower()
        out.append(f"// {file}: {fw}x{fh}, ascent {font['ascent']}, {len(cps)} glyphs")
        out.append(f"static const uint16_t {tag}_codepoints[] = {{")
        for i in range(0, len(cps), 12):
            out.append("    " + ", ".join(f"0x{c:04X}" for c in cps[i:i + 12]) + ",")
        out.append("};")
        out.append(f"static const uint8_t {tag}_bitmap[] = {{")
        for c in cps:
            data = render(font, glyphs[c])
            label = chr(c) if 0x20 < c < 0x7F and chr(c) not in "\\" else f"U+{c:04X}"
            out.append("    " + ", ".join(f"0x{b:02X}" for b in data) + f",  // {label}")
        out.append("};")
        fallback = cps.index(ord("?"))
        out.append(f"const Font {name} = {{{fw}, {fh}, {font['ascent']}, {bpr}, {len(cps)}, {fallback}, "
                   f"{tag}_codepoints, {tag}_bitmap}};")
        out.append("")
    out.append("} // namespace ui")
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
